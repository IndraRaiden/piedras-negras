          pueblo, un Plan Municipal de Desarrollo que refleje las verdaderas prioridades de la ciudadanía. 
          Es así como se pretende consolidar una administración humanista, orientada al servicio, que 
          cumple con su palabra y rinde cuentas de manera abierta y transparente. 
        </p>
        
